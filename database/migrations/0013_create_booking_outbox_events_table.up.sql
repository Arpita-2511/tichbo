-- The publisher's own query shape: PENDING rows, oldest first, a bounded
-- batch at a time. A partial index (only PENDING rows) keeps the sweep
-- cheap as the table grows, since PUBLISHED rows are retained and will
-- vastly outnumber PENDING ones in the steady state — the same "index
-- only what the sweep queries" reasoning already used for
-- idx_payments_booking_sync_status_pending in migration 0012.
--
-- Known test-environment limitation (see docs/architecture.md §25.4):
-- this project's H2 test version does not support partial/filtered
-- indexes, so this index is exercised only against the real PostgreSQL
-- migration, not by any H2-backed test — the same documented gap
-- uq_payments_one_active_per_booking already has.
CREATE INDEX idx_booking_outbox_events_pending_created_at
    ON booking_outbox_events (created_at)
    WHERE status = 'PENDING';

CREATE TRIGGER trg_booking_outbox_events_set_updated_at
    BEFORE UPDATE ON booking_outbox_events
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();
