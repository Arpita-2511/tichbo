-- Migration: 0013_create_booking_outbox_events_table
-- Description: Creates `booking_outbox_events` — the Transactional Outbox
--              (Phase 16 Step 2) for booking-service's own domain events.
--              A business transaction (e.g. creating a booking) writes its
--              normal row AND a row here in the SAME database transaction,
--              so the two can never disagree: an event exists if and only
--              if the state change it describes was actually committed. A
--              separate scheduled publisher (OutboxPublisher) reads PENDING
--              rows here and publishes them to Kafka independently, marking
--              PUBLISHED only after a real broker acknowledgement. See
--              docs/architecture.md §47.9 (the design) and §48 (this
--              implementation).
-- Depends on: nothing (aggregate_id is a plain UUID reference, not a FK —
--             this table must support any future aggregate type, not only
--             bookings; see the table comment below).

-- Table name is prefixed `booking_`, unlike every domain table so far
-- (bookings, payments, ...), because "outbox_events" is not a unique
-- domain noun the way those are — it is generic outbox-pattern
-- infrastructure that any future producing service (payment-service,
-- catalog-service, user-service) will eventually need its own copy of.
-- All of Eventtick's tables currently share one physical database
-- (docs/architecture.md §17: database-per-service is a future target, not
-- required today), so an unprefixed `outbox_events` name would collide the
-- moment a second service adds its own outbox table. The prefix avoids
-- that collision now rather than requiring a rename later.
CREATE TABLE booking_outbox_events (
    event_id        UUID          PRIMARY KEY,
    event_type      VARCHAR(100)  NOT NULL,
    aggregate_type  VARCHAR(50)   NOT NULL,
    aggregate_id    UUID          NOT NULL,
    topic           VARCHAR(100)  NOT NULL,
    payload         TEXT          NOT NULL,
    occurred_at     TIMESTAMPTZ   NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    attempts        INT           NOT NULL DEFAULT 0,
    last_error      TEXT,
    published_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT chk_booking_outbox_events_status
        CHECK (status IN ('PENDING', 'PUBLISHED', 'FAILED')),
    CONSTRAINT chk_booking_outbox_events_attempts_nonneg
        CHECK (attempts >= 0),
    CONSTRAINT chk_booking_outbox_events_published_at_consistency
        CHECK (
            (status = 'PUBLISHED' AND published_at IS NOT NULL)
            OR (status <> 'PUBLISHED' AND published_at IS NULL)
        )
);

